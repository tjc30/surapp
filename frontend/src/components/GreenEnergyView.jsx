import AreaDataStatus from './AreaDataStatus';
import React, { useState } from 'react';
import { Chart as ChartJS, CategoryScale, LinearScale, PointElement, LineElement, Tooltip, Legend } from 'chart.js';
import { Line } from 'react-chartjs-2';
import { Zap, Layers, Activity, Calendar, Table as TableIcon, Download } from 'lucide-react';
import csv from '../../../input/clean-energy/global_clean_power_share.csv?raw';

ChartJS.register(CategoryScale, LinearScale, PointElement, LineElement, Tooltip, Legend);

const [header, ...rows] = csv.trim().split(/\r?\n/).map(line => line.split(','));
const records = rows.map(row => Object.fromEntries(header.map((key, index) => [key, key === 'country' ? row[index] : Number(row[index])]))).sort((a, b) => a.year - b.year);
const metrics = [
  { key: 'renewables_share_elec', label: 'Renewables', color: '#34D399' },
  { key: 'low_carbon_share_elec', label: 'Low-carbon', color: '#38BDF8' },
  { key: 'solar_share_elec', label: 'Solar', color: '#FBBF24' },
  { key: 'wind_share_elec', label: 'Wind', color: '#C4B5FD' },
];
const first = records[0];
const latest = records[records.length - 1];

export default function GreenEnergyView({ onNavigate }) {
  const [tab, setTab] = useState('chart');
  const [startYear, setStartYear] = useState(first.year);
  const filtered = records.filter(record => record.year >= startYear);
  const exportCsv = () => {
    const content = [header.join(','), ...filtered.map(record => header.map(key => record[key]).join(','))].join('\n');
    const url = URL.createObjectURL(new Blob([content], { type: 'text/csv;charset=utf-8;' }));
    const link = document.createElement('a');
    link.href = url;
    link.download = `global-clean-power-${startYear}-${latest.year}.csv`;
    link.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  };

  return (
    <div className="green-energy-view">
      <AreaDataStatus>
        <span className="badge-ready">World · {first.year}–{latest.year} · {records.length} annual records</span>
      </AreaDataStatus>

      <div className="wildfires-hero-card">
        <div className="wildfires-hero-content">
          <Zap size={36} className="text-emerald" aria-hidden="true" />
          <div className="wildfires-hero-text">
            <div className="placeholder-category-pill">Clean Energy Solutions · Global Electricity</div>
            <h2 className="wildfires-hero-title">Green Energy Increases &amp; Transition</h2>
            <p className="wildfires-hero-desc">Track the changing share of global electricity generated by renewables, low-carbon sources, solar, and wind. Explore {records.length} years of clean power transition in the supplied dataset.</p>
          </div>
        </div>
      </div>

      <div className="kpi-metrics-grid">
        {metrics.map(metric => {
          const change = latest[metric.key] - first[metric.key];
          return <div key={metric.key} className="kpi-metric-card">
            <div className="kpi-card-header"><span className="kpi-card-label">{metric.label} · {latest.year}</span></div>
            <div className="kpi-card-main-val" style={{ color: metric.color }}>{latest[metric.key].toFixed(2)}%</div>
            <div className="kpi-card-sub">{change >= 0 ? '+' : ''}{change.toFixed(2)} percentage points since {first.year}</div>
          </div>;
        })}
      </div>

      <div className="controls-panel">
        <div className="control-row">
          <span className="control-row-label"><Layers size={14} /> View Mode:</span>
          <div className="selection-boxes-group">
            <button type="button" className={`selection-box-btn ${tab === 'chart' ? 'active' : ''}`} aria-pressed={tab === 'chart'} onClick={() => setTab('chart')}><Activity size={14} /> Interactive Chart</button>
            <button type="button" className={`selection-box-btn ${tab === 'table' ? 'active' : ''}`} aria-pressed={tab === 'table'} onClick={() => setTab('table')}><TableIcon size={14} /> Raw Records <span className="selection-count-pill">{filtered.length}</span></button>
          </div>
        </div>
        <div className="control-row">
          <span className="control-row-label"><Calendar size={14} /> Time Horizon:</span>
          <div className="selection-boxes-group">
            {[first.year, 2010, 2020].map(year => <button key={year} type="button" className={`selection-box-btn ${startYear === year ? 'active' : ''}`} aria-pressed={startYear === year} onClick={() => setStartYear(year)}>{year}–{latest.year}</button>)}
          </div>
        </div>
      </div>

      <section className="wildfires-chart-card">
        <div className="chart-toolbar-container">
          <div><h3 className="chart-section-title">Global clean power share ({startYear}–{latest.year})</h3><p className="chart-section-subtitle">Share of total electricity generation (%) · World</p></div>
          <button type="button" className="btn btn-secondary btn-sm" onClick={exportCsv}><Download size={14} /> Export CSV</button>
        </div>
        {tab === 'chart' ? <>
          <div className="green-energy-chart" role="img" aria-label={`Line chart of global renewable, low-carbon, solar, and wind electricity shares from ${startYear} to ${latest.year}. Exact values are available in Raw Records.`}>
            <Line data={{ labels: filtered.map(record => record.year), datasets: metrics.map(metric => ({ label: metric.label, data: filtered.map(record => record[metric.key]), borderColor: metric.color, backgroundColor: metric.color, borderWidth: 2.5, pointRadius: 2, pointHoverRadius: 6, tension: 0.2 })) }} options={{ responsive: true, maintainAspectRatio: false, interaction: { mode: 'index', intersect: false }, plugins: { legend: { position: 'bottom', labels: { color: '#E2E8F0', padding: 20, usePointStyle: true } }, tooltip: { callbacks: { label: context => `${context.dataset.label}: ${context.parsed.y.toFixed(3)}%` } } }, scales: { x: { ticks: { color: '#94A3B8', maxTicksLimit: 9 }, grid: { color: 'rgba(255,255,255,0.04)' } }, y: { min: 0, suggestedMax: 50, title: { display: true, text: 'Share of electricity generation (%)', color: '#94A3B8' }, ticks: { color: '#94A3B8', callback: value => `${value}%` }, grid: { color: 'rgba(255,255,255,0.08)' } } } }} />
          </div>
          <p className="chart-section-subtitle">Hover over a year to compare shares. Click a legend item to hide or show a series.</p>
        </> : <div className="green-energy-table-wrap"><table className="green-energy-table">
          <caption>Global electricity generation shares, {startYear}–{latest.year}. All share values are percentages.</caption>
          <thead><tr><th scope="col">Year</th><th scope="col">Country / region</th>{metrics.map(metric => <th scope="col" key={metric.key}>{metric.label} (%)</th>)}</tr></thead>
          <tbody>{filtered.map(record => <tr key={record.year}><th scope="row">{record.year}</th><td>{record.country}</td>{metrics.map(metric => <td key={metric.key}>{record[metric.key].toFixed(3)}</td>)}</tr>)}</tbody>
        </table></div>}
      </section>

      <section className="wildfires-chart-card">
        <h3 className="chart-section-title">Reading the transition</h3>
        <p>Solar and wind together account for {(latest.solar_share_elec + latest.wind_share_elec).toFixed(2)}% of global electricity in {latest.year}, compared with {(first.solar_share_elec + first.wind_share_elec).toFixed(2)}% in {first.year}.</p>
        <p>These series overlap: solar and wind are included in renewables; low-carbon electricity includes renewables and nuclear. The four lines should not be added together. Shares describe electricity generation, rather than total energy use or installed capacity.</p>
        <p className="chart-section-subtitle">Dataset: global_clean_power_share.csv · {records.length} annual World records · {first.year}–{latest.year}. The supplied CSV does not include publisher, methodology, or revision metadata.</p>
      </section>
    </div>
  );
}
